"""
Persistence Repository for ShadowAgent.
Implements the exact schema expected by the project:
  - public.simulation_runs (id, status, started_at, completed_at, metrics)
  - public.network_nodes (id, simulation_run_id, node_key, label, node_type, metadata)
  - public.simulation_events (id, simulation_run_id, occurred_at, agent, severity, message, node_key, action, details)

Provides both SupabaseRepository and InMemoryRepository fallback.
"""

from __future__ import annotations

import logging
from abc import ABC, abstractmethod
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

logger = logging.getLogger("shadowagent.repository")


class SimulationRepository(ABC):
    """Abstract interface for ShadowAgent simulation persistence."""

    @abstractmethod
    def create_run(self, run_id: str, started_at: str) -> bool:
        """Create a new simulation_runs record with status='in_progress'."""
        pass

    @abstractmethod
    def save_network_nodes(
        self,
        run_id: str,
        nodes: List[Any],
        node_statuses: Dict[str, str],
    ) -> bool:
        """Save network nodes associated with the simulation run."""
        pass

    @abstractmethod
    def save_events(
        self,
        run_id: str,
        events: List[Any],
    ) -> bool:
        """Save events generated by the simulation run."""
        pass

    @abstractmethod
    def complete_run(
        self,
        run_id: str,
        completed_at: str,
        metrics: Any,
        status: str = "completed",
    ) -> bool:
        """Update simulation_runs with completed status and final metrics."""
        pass

    @abstractmethod
    def fail_run(
        self,
        run_id: str,
        error_message: str,
        completed_at: Optional[str] = None,
    ) -> bool:
        """Mark simulation_runs as failed with error details."""
        pass

    @abstractmethod
    def list_runs(self, limit: int = 50) -> List[Dict[str, Any]]:
        """Retrieve recent simulation runs."""
        pass

    @abstractmethod
    def get_run(self, run_id: str) -> Optional[Dict[str, Any]]:
        """Retrieve full details of a run, including nodes and events."""
        pass


# ── Supabase Implementation ──────────────────────────────────────────────────

class SupabaseRepository(SimulationRepository):
    """
    Persists simulation runs, network nodes, and events to Supabase PostgreSQL.
    Follows the strict expected schema and avoids duplicate inserts.
    """

    def __init__(self, client: Any) -> None:
        self.client = client
        self._memory_backup = InMemoryRepository()

    def create_run(self, run_id: str, started_at: str) -> bool:
        self._memory_backup.create_run(run_id, started_at)
        try:
            payload = {
                "id": run_id,
                "status": "in_progress",
                "started_at": started_at,
                "completed_at": None,
                "metrics": {},
            }
            # Use upsert to prevent duplicates if create_run is retried
            self.client.table("simulation_runs").upsert(payload, on_conflict="id").execute()
            return True
        except Exception as exc:
            logger.error("[SupabaseRepository] create_run failed: %s", type(exc).__name__)
            return False

    def save_network_nodes(
        self,
        run_id: str,
        nodes: List[Any],
        node_statuses: Dict[str, str],
    ) -> bool:
        self._memory_backup.save_network_nodes(run_id, nodes, node_statuses)
        if not nodes:
            return True
        try:
            # Delete any existing nodes for this run_id first to prevent duplicate inserts
            try:
                self.client.table("network_nodes").delete().eq("simulation_run_id", run_id).execute()
            except Exception:
                pass

            node_records = []
            for n in nodes:
                # Handle both dicts and Pydantic models
                node_id = getattr(n, "id", None) or n.get("id")
                label = getattr(n, "label", None) or n.get("label", "")
                node_type = getattr(n, "type", None) or n.get("type", "server")
                risk_score = getattr(n, "risk_score", None) if hasattr(n, "risk_score") else (n.get("risk_score") if isinstance(n, dict) else 0.0)
                x = getattr(n, "x", None) if hasattr(n, "x") else (n.get("x") if isinstance(n, dict) else 0)
                y = getattr(n, "y", None) if hasattr(n, "y") else (n.get("y") if isinstance(n, dict) else 0)
                desc = getattr(n, "description", "") or (n.get("description", "") if isinstance(n, dict) else "")

                node_records.append({
                    "simulation_run_id": run_id,
                    "node_key": str(node_id),
                    "label": str(label),
                    "node_type": str(node_type),
                    "metadata": {
                        "status": node_statuses.get(str(node_id), "clean"),
                        "risk_score": float(risk_score or 0.0),
                        "x": float(x or 0.0),
                        "y": float(y or 0.0),
                        "description": str(desc),
                    },
                })

            self.client.table("network_nodes").insert(node_records).execute()
            return True
        except Exception as exc:
            logger.error("[SupabaseRepository] save_network_nodes failed: %s", type(exc).__name__)
            return False

    def save_events(
        self,
        run_id: str,
        events: List[Any],
    ) -> bool:
        self._memory_backup.save_events(run_id, events)
        if not events:
            return True
        try:
            # Delete any existing events for this run_id to avoid duplicate records
            try:
                self.client.table("simulation_events").delete().eq("simulation_run_id", run_id).execute()
            except Exception:
                pass

            event_records = []
            for e in events:
                evt_id = getattr(e, "id", None) or (e.get("id") if isinstance(e, dict) else "")
                ts = getattr(e, "timestamp", None) or (e.get("timestamp") if isinstance(e, dict) else datetime.now(timezone.utc).isoformat())
                agent = getattr(e, "agent", None) or (e.get("agent") if isinstance(e, dict) else "Unknown")
                severity = getattr(e, "severity", None) or (e.get("severity") if isinstance(e, dict) else "low")
                message = getattr(e, "message", None) or (e.get("message") if isinstance(e, dict) else "")
                node_id = getattr(e, "node_id", None) or (e.get("node_id") if isinstance(e, dict) else "")
                action = getattr(e, "action", None) or (e.get("action") if isinstance(e, dict) else "")
                success = getattr(e, "success", True) if hasattr(e, "success") else (e.get("success", True) if isinstance(e, dict) else True)
                phase = getattr(e, "phase", 1) if hasattr(e, "phase") else (e.get("phase", 1) if isinstance(e, dict) else 1)

                event_records.append({
                    "simulation_run_id": run_id,
                    "occurred_at": ts,
                    "agent": str(agent),
                    "severity": str(severity),
                    "message": str(message),
                    "node_key": str(node_id),
                    "action": str(action),
                    "details": {
                        "success": bool(success),
                        "phase": int(phase),
                        "event_id": str(evt_id),
                    },
                })

            self.client.table("simulation_events").insert(event_records).execute()
            return True
        except Exception as exc:
            logger.error("[SupabaseRepository] save_events failed: %s", type(exc).__name__)
            return False

    def complete_run(
        self,
        run_id: str,
        completed_at: str,
        metrics: Any,
        status: str = "completed",
    ) -> bool:
        self._memory_backup.complete_run(run_id, completed_at, metrics, status)
        try:
            metrics_dict = metrics.model_dump() if hasattr(metrics, "model_dump") else dict(metrics)
            payload = {
                "status": status,
                "completed_at": completed_at,
                "metrics": metrics_dict,
            }
            self.client.table("simulation_runs").update(payload).eq("id", run_id).execute()
            return True
        except Exception as exc:
            logger.error("[SupabaseRepository] complete_run failed: %s", type(exc).__name__)
            return False

    def fail_run(
        self,
        run_id: str,
        error_message: str,
        completed_at: Optional[str] = None,
    ) -> bool:
        self._memory_backup.fail_run(run_id, error_message, completed_at)
        try:
            payload = {
                "status": "failed",
                "completed_at": completed_at or datetime.now(timezone.utc).isoformat(),
                "metrics": {"error": error_message},
            }
            self.client.table("simulation_runs").update(payload).eq("id", run_id).execute()
            return True
        except Exception as exc:
            logger.error("[SupabaseRepository] fail_run failed: %s", type(exc).__name__)
            return False

    def list_runs(self, limit: int = 50) -> List[Dict[str, Any]]:
        try:
            resp = (
                self.client.table("simulation_runs")
                .select("id,status,started_at,completed_at,metrics")
                .order("started_at", desc=True)
                .limit(limit)
                .execute()
            )
            data = resp.data or []
            if not data and self._memory_backup.runs:
                return self._memory_backup.list_runs(limit)
            results = []
            for r in data:
                m = r.get("metrics") or {}
                results.append({
                    "id": r.get("id"),
                    "run_id": r.get("id"),
                    "status": r.get("status"),
                    "started_at": r.get("started_at"),
                    "completed_at": r.get("completed_at"),
                    "metrics": m,
                    "total_events": m.get("total_events", 0),
                    "threats_detected": m.get("threats_detected", 0),
                    "attacks_blocked": m.get("attacks_blocked", 0),
                    "detection_rate": m.get("detection_rate", 0.0),
                    "data_protected": m.get("data_protected", True),
                    "compromised_assets": m.get("compromised_assets", 0),
                })
            return results
        except Exception as exc:
            logger.error("[SupabaseRepository] list_runs failed: %s", type(exc).__name__)
            return self._memory_backup.list_runs(limit)

    def get_run(self, run_id: str) -> Optional[Dict[str, Any]]:
        try:
            # 1. Fetch run
            run_resp = self.client.table("simulation_runs").select("*").eq("id", run_id).limit(1).execute()
            if not run_resp.data:
                return self._memory_backup.get_run(run_id)
            run_row = run_resp.data[0]

            # 2. Fetch nodes
            nodes_resp = self.client.table("network_nodes").select("*").eq("simulation_run_id", run_id).execute()
            nodes_data = nodes_resp.data or []

            # 3. Fetch events
            events_resp = self.client.table("simulation_events").select("*").eq("simulation_run_id", run_id).order("occurred_at").execute()
            events_data = events_resp.data or []

            # Standardize event items for frontend display
            formatted_events = []
            for ev in events_data:
                details = ev.get("details") or {}
                formatted_events.append({
                    "id": ev.get("id"),
                    "event_id": details.get("event_id", ev.get("id")),
                    "timestamp": ev.get("occurred_at"),
                    "occurred_at": ev.get("occurred_at"),
                    "agent": ev.get("agent"),
                    "action": ev.get("action"),
                    "node_id": ev.get("node_key"),
                    "node_key": ev.get("node_key"),
                    "severity": ev.get("severity"),
                    "message": ev.get("message"),
                    "success": details.get("success", True),
                    "phase": details.get("phase", 1),
                    "details": details,
                })

            return {
                "run": run_row,
                "run_id": run_id,
                "status": run_row.get("status"),
                "started_at": run_row.get("started_at"),
                "completed_at": run_row.get("completed_at"),
                "metrics": run_row.get("metrics") or {},
                "nodes": nodes_data,
                "events": formatted_events,
            }
        except Exception as exc:
            logger.error("[SupabaseRepository] get_run failed: %s", type(exc).__name__)
            return self._memory_backup.get_run(run_id)


# ── In-Memory Implementation ─────────────────────────────────────────────────

class InMemoryRepository(SimulationRepository):
    """
    Thread-safe in-memory simulation repository.
    Used when Supabase is not configured or as an isolated test double.
    """

    def __init__(self) -> None:
        self.runs: Dict[str, Dict[str, Any]] = {}
        self.nodes: Dict[str, List[Dict[str, Any]]] = {}
        self.events: Dict[str, List[Dict[str, Any]]] = {}

    def create_run(self, run_id: str, started_at: str) -> bool:
        self.runs[run_id] = {
            "id": run_id,
            "status": "in_progress",
            "started_at": started_at,
            "completed_at": None,
            "metrics": {},
        }
        self.nodes[run_id] = []
        self.events[run_id] = []
        return True

    def save_network_nodes(
        self,
        run_id: str,
        nodes: List[Any],
        node_statuses: Dict[str, str],
    ) -> bool:
        node_records = []
        for n in nodes:
            node_id = getattr(n, "id", None) or (n.get("id") if isinstance(n, dict) else "")
            label = getattr(n, "label", None) or (n.get("label", "") if isinstance(n, dict) else "")
            node_type = getattr(n, "type", None) or (n.get("type", "server") if isinstance(n, dict) else "server")
            risk_score = getattr(n, "risk_score", None) if hasattr(n, "risk_score") else (n.get("risk_score") if isinstance(n, dict) else 0.0)
            x = getattr(n, "x", None) if hasattr(n, "x") else (n.get("x") if isinstance(n, dict) else 0)
            y = getattr(n, "y", None) if hasattr(n, "y") else (n.get("y") if isinstance(n, dict) else 0)
            desc = getattr(n, "description", "") or (n.get("description", "") if isinstance(n, dict) else "")

            node_records.append({
                "simulation_run_id": run_id,
                "node_key": str(node_id),
                "label": str(label),
                "node_type": str(node_type),
                "metadata": {
                    "status": node_statuses.get(str(node_id), "clean"),
                    "risk_score": float(risk_score or 0.0),
                    "x": float(x or 0.0),
                    "y": float(y or 0.0),
                    "description": str(desc),
                },
            })
        self.nodes[run_id] = node_records
        return True

    def save_events(
        self,
        run_id: str,
        events: List[Any],
    ) -> bool:
        event_records = []
        for e in events:
            evt_id = getattr(e, "id", None) or (e.get("id") if isinstance(e, dict) else "")
            ts = getattr(e, "timestamp", None) or (e.get("timestamp") if isinstance(e, dict) else datetime.now(timezone.utc).isoformat())
            agent = getattr(e, "agent", None) or (e.get("agent") if isinstance(e, dict) else "Unknown")
            severity = getattr(e, "severity", None) or (e.get("severity") if isinstance(e, dict) else "low")
            message = getattr(e, "message", None) or (e.get("message") if isinstance(e, dict) else "")
            node_id = getattr(e, "node_id", None) or (e.get("node_id") if isinstance(e, dict) else "")
            action = getattr(e, "action", None) or (e.get("action") if isinstance(e, dict) else "")
            success = getattr(e, "success", True) if hasattr(e, "success") else (e.get("success", True) if isinstance(e, dict) else True)
            phase = getattr(e, "phase", 1) if hasattr(e, "phase") else (e.get("phase", 1) if isinstance(e, dict) else 1)

            event_records.append({
                "id": str(evt_id),
                "simulation_run_id": run_id,
                "occurred_at": ts,
                "timestamp": ts,
                "agent": str(agent),
                "severity": str(severity),
                "message": str(message),
                "node_key": str(node_id),
                "node_id": str(node_id),
                "action": str(action),
                "success": bool(success),
                "phase": int(phase),
                "details": {
                    "success": bool(success),
                    "phase": int(phase),
                    "event_id": str(evt_id),
                },
            })
        self.events[run_id] = event_records
        return True

    def complete_run(
        self,
        run_id: str,
        completed_at: str,
        metrics: Any,
        status: str = "completed",
    ) -> bool:
        if run_id not in self.runs:
            return False
        metrics_dict = metrics.model_dump() if hasattr(metrics, "model_dump") else dict(metrics)
        self.runs[run_id]["status"] = status
        self.runs[run_id]["completed_at"] = completed_at
        self.runs[run_id]["metrics"] = metrics_dict
        return True

    def fail_run(
        self,
        run_id: str,
        error_message: str,
        completed_at: Optional[str] = None,
    ) -> bool:
        if run_id not in self.runs:
            self.runs[run_id] = {
                "id": run_id,
                "started_at": datetime.now(timezone.utc).isoformat(),
            }
        self.runs[run_id]["status"] = "failed"
        self.runs[run_id]["completed_at"] = completed_at or datetime.now(timezone.utc).isoformat()
        self.runs[run_id]["metrics"] = {"error": error_message}
        return True

    def list_runs(self, limit: int = 50) -> List[Dict[str, Any]]:
        # Order by started_at descending
        sorted_runs = sorted(
            self.runs.values(),
            key=lambda r: r.get("started_at", ""),
            reverse=True,
        )[:limit]

        results = []
        for r in sorted_runs:
            m = r.get("metrics") or {}
            results.append({
                "id": r.get("id"),
                "run_id": r.get("id"),
                "status": r.get("status"),
                "started_at": r.get("started_at"),
                "completed_at": r.get("completed_at"),
                "metrics": m,
                "total_events": m.get("total_events", 0),
                "threats_detected": m.get("threats_detected", 0),
                "attacks_blocked": m.get("attacks_blocked", 0),
                "detection_rate": m.get("detection_rate", 0.0),
                "data_protected": m.get("data_protected", True),
                "compromised_assets": m.get("compromised_assets", 0),
            })
        return results

    def get_run(self, run_id: str) -> Optional[Dict[str, Any]]:
        if run_id not in self.runs:
            return None
        run_row = self.runs[run_id]
        return {
            "run": run_row,
            "run_id": run_id,
            "status": run_row.get("status"),
            "started_at": run_row.get("started_at"),
            "completed_at": run_row.get("completed_at"),
            "metrics": run_row.get("metrics") or {},
            "nodes": self.nodes.get(run_id, []),
            "events": self.events.get(run_id, []),
        }


# ── Global Repository Factory & Registry ──────────────────────────────────────

_active_repo: Optional[SimulationRepository] = None


def get_repository() -> SimulationRepository:
    """
    Return the active repository.
    Instantiates SupabaseRepository if configured, otherwise InMemoryRepository.
    """
    global _active_repo
    if _active_repo is not None:
        return _active_repo

    from .supabase_client import get_supabase_client
    client = get_supabase_client()
    if client is not None:
        _active_repo = SupabaseRepository(client)
    else:
        _active_repo = InMemoryRepository()

    return _active_repo


def set_repository(repo: SimulationRepository) -> None:
    """Explicitly inject a repository (useful for mocking during tests)."""
    global _active_repo
    _active_repo = repo


def reset_repository() -> None:
    """Reset repository back to default state."""
    global _active_repo
    _active_repo = None
